#!/usr/bin/env python3
"""Generate ``docs/_generated/COUNTS.md``: the repository's measured numbers.

Every count in the generated document is derived from tracked files, the gate's own
tool pins, and the arm timings recorded by ``./run.sh measure``. Nothing in the
generated document is hand-written, so documentation prose links here instead of
copying a literal that can drift.

Usage:
    python3 scripts/docgen/counts.py            # write the document
    python3 scripts/docgen/counts.py --check    # fail if the document is stale
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path("docs/_generated/COUNTS.md")
TIMINGS = Path("docs/_generated/timings.json")
PIN = Path(".github/gnn-pin.json")
TOOLS = Path("scripts/gate_tools.json")
DOCS_DIR = Path("docs")

# Canonical arm order for the timing table; `check` and `all` are compositions.
GATE_ARMS = ("lint", "links", "gnn")


def tracked(pattern: str) -> list[str]:
    result = subprocess.run(
        # Tracked plus untracked-but-not-ignored, so the document is already current
        # for a page that has been written but not yet staged.
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", pattern],
        cwd=ROOT,
        capture_output=True,
        check=True,
    )
    return [path for path in result.stdout.decode().split("\0") if path]


def read_json(relative: Path) -> dict:
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def seconds(value: float) -> str:
    return f"{value:.2f}"


def render() -> str:
    markdown = tracked("*.md")
    sketches = tracked("*.gnn.md")
    docs_pages = [name for name in markdown if name.startswith(f"{DOCS_DIR.as_posix()}/")]
    pin = read_json(PIN)
    tools = read_json(TOOLS)
    timings = read_json(TIMINGS)

    rows = [
        ("Tracked files", len(tracked("*"))),
        ("Tracked Markdown files", len(markdown)),
        ("Pages under `docs/`", len(docs_pages)),
        ("GNN sketches (`*.gnn.md`)", len(sketches)),
    ]
    lines = [
        "# Measured counts and gate timings",
        "",
        "<!-- Generated by scripts/docgen/counts.py from tracked files. Do not edit. -->",
        "",
        "Refresh with `./run.sh counts`; re-measure the gate arms with `./run.sh measure`",
        "and regenerate again. Prose links to this page instead of copying a number.",
        "",
        "## Inventory",
        "",
        "| Metric | Value |",
        "| --- | --- |",
    ]
    lines += [f"| {label} | {value} |" for label, value in rows]

    lines += [
        "",
        "## Gate pins",
        "",
        "| Item | Value |",
        "| --- | --- |",
        f"| GNN pin schema | `{pin['schema']}` |",
        f"| GNN pin repository | `{pin['repository']}` |",
        f"| GNN pin tag | `{pin['tag']}` |",
        f"| GNN pin revision | `{pin['revision']}` |",
        f"| GNN pin recorded | {pin['recorded']} |",
        f"| markdownlint-cli2 | {tools['markdownlint-cli2']} |",
        f"| markdown-link-check | {tools['markdown-link-check']} |",
        "",
        "## Gate arms",
        "",
        "| Arm | Wall time (s) |",
        "| --- | --- |",
    ]
    missing = [arm for arm in GATE_ARMS if arm not in timings["arms"]]
    if missing:
        raise SystemExit(f"timings.json is missing arms: {', '.join(missing)}")
    lines += [f"| `./run.sh {arm}` | {seconds(timings['arms'][arm])} |" for arm in GATE_ARMS]
    lines += [
        "",
        "`./run.sh check` runs `counts --check`, `test`, `lint` and `links`; `./run.sh all` adds `gnn`.",
        "",
        f"Measured {timings['recorded']} on {timings['host']} with Node {timings['node']}.",
        "Protocol: " + timings["protocol"].rstrip(".") + ".",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the generated document is current instead of writing it",
    )
    args = parser.parse_args(argv)

    target = ROOT / OUTPUT
    rendered = render()
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != rendered:
            print(
                f"{OUTPUT} is stale: run ./run.sh counts and commit the result",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT} is current")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
